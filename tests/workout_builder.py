"""Use the builder in both absolute watts and percentages; verify the saved plan."""
import os
from playwright.sync_api import expect, sync_playwright
with sync_playwright() as driver:
    browser=driver.chromium.launch(executable_path=os.getenv('CHROME_PATH'))
    page=browser.new_page()
    page.goto(os.getenv('RIDE_URL','http://127.0.0.1:8791/'))
    page.locator('#loading').wait_for(state='detached',timeout=120000)
    page.locator('#startWorkout').click()
    page.get_by_role('button',name='Build a workout').click()
    expect(page.locator('.builderPreview')).to_contain_text('42:00')
    expect(page.locator('.builderChart span')).to_have_count(7)
    page.get_by_label('Workout name').fill('Threshold test')
    page.get_by_label('Power targets').select_option('ftp')
    expect(page.locator('.builderPreview')).to_contain_text('Enter a reference FTP')
    page.get_by_label('Reference FTP (W)').fill('240')
    page.get_by_label('Effort target (% FTP)').fill('110')
    page.get_by_label('Easy target (% FTP)').fill('55')
    expect(page.locator('.builderPreview')).to_contain_text('132–264 W')
    page.get_by_role('button',name='Save workout').click()
    row=page.locator('.planRow').filter(has_text='Threshold test')
    expect(row).to_contain_text('110% FTP (264 W)')
    row.get_by_role('button',name='Edit').click()
    expect(page.get_by_label('Reference FTP (W)')).to_have_value('240')
    page.get_by_label('Power targets').select_option('watts')
    expect(page.get_by_label('Effort target (W)')).to_have_value('264')
    page.get_by_label('Power targets').select_option('ftp')
    page.get_by_role('button',name='Save workout').click()
    row.get_by_role('button',name='Ride',exact=True).click()
    expect(page.locator('#targetPower')).to_have_text('132 W')
    page.locator('#nextStep').click()
    expect(page.locator('#targetPower')).to_have_text('264 W')
    page.locator('#intensityUp').click()
    expect(page.locator('#targetPower')).to_have_text('277 W')
    page.locator('#finishWorkout').click()
    expect(page.locator('.reviewChart')).to_be_visible()
    print('Watts and percentage builder, live preview, saved edit, interval targets and intensity passed')
    browser.close()
